#Cuenta regresiva
#Crear un programa que muestre una ceunta atrás desde un numero n Hasta 0 usando bucle WHILE
n = int(input("Ingresa un número para la cuenta regresiva: "))

# Bucle while para contar hacia atrás
while n >= 0:
    print(f"Numero: {n}") 
    n -= 1  #Hacemos que se vaya restando el numero introducido
 